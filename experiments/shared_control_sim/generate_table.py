#!/usr/bin/env python3
"""Create readable experiment tables from a shared-control summary CSV."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def format_percent(value: str) -> str:
    return f"{float(value) * 100:.1f}%"


def render_table(rows: list[dict[str, str]]) -> str:
    headers = ["Condition", "Trials", "Success", "Collision", "Timeout", "Mean steps"]
    values = [
        [
            row["condition"],
            row["trials"],
            format_percent(row["success_rate"]),
            format_percent(row["collision_rate"]),
            format_percent(row["timeout_rate"]),
            f"{float(row['mean_steps']):.1f}",
        ]
        for row in rows
    ]
    widths = [max(len(header), *(len(row[index]) for row in values)) for index, header in enumerate(headers)]
    header = "| " + " | ".join(name.ljust(widths[index]) for index, name in enumerate(headers)) + " |"
    separator = "|" + "|".join("-" * (width + 2) for width in widths) + "|"
    body = ["| " + " | ".join(cell.ljust(widths[index]) for index, cell in enumerate(row)) + " |" for row in values]
    return "\n".join([header, separator, *body]) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a Markdown summary table for shared-control experiments.")
    parser.add_argument("summary_csv", type=Path, help="Path to summary.csv generated by run_experiment.py")
    parser.add_argument("--output", type=Path, help="Output Markdown path; defaults to summary_table.md beside the CSV")
    args = parser.parse_args()

    with args.summary_csv.open(newline="", encoding="utf-8") as summary_file:
        rows = list(csv.DictReader(summary_file))
    if not rows:
        raise ValueError(f"No experiment rows found in {args.summary_csv}")

    table = render_table(rows)
    output = args.output or args.summary_csv.with_name("summary_table.md")
    output.write_text("# Shared-Control Experiment Summary\n\n" + table, encoding="utf-8")
    print(table, end="")
    print(f"wrote table to {output}")


if __name__ == "__main__":
    main()